r"""
Standalone source export of compiled characteristic exponents.

:func:`export_source` turns a :class:`~spxa.compile.process.CompiledProcess`
into the text of a self-contained Python module that needs only NumPy (and
SciPy when the exponent uses :math:`\Gamma`, digamma or Bessel functions).
The module defines

* ``NAMES`` and ``THETA0`` — the free parameters and their compiled values;
* ``psi(u, theta=THETA0)`` — :math:`\psi(u;\theta)`;
* ``psi_and_grad(u, theta=THETA0)`` — :math:`\psi` and
  :math:`\partial\psi/\partial\theta` (last axis), when exported with
  ``grad=True``;
* ``char_func(u, t=1.0, theta=THETA0)`` — :math:`e^{t\psi(u)}`.

The functions are the *general* programs (no parameter branch is
specialised away), so they are valid for every ``theta``; their arithmetic
is that of the NumPy backend, so they agree with the in-process kernel to
the last bit. Opaque leaves and the order derivative of the generalised
hyperbolic :math:`K_\lambda` (a free ``lambda_param``) need spxa itself and
cannot be exported.
"""

from __future__ import annotations

import math
import re
from typing import Any, List

from spxa.compile import ir as I
from spxa.compile._numeric import _SINC_D1_COEFFS, _SINC_SERIES_RADIUS
from spxa.compile.codegen import generate
from spxa.compile.ir import CompileError

__all__ = ["export_source"]

_SINC_SRC = """
def _sinc(z):
    z = np.asarray(z)
    small = z == 0
    safe = np.where(small, 1.0, z)
    return np.where(small, 1.0, np.sin(safe) / safe)[()]
"""

_SINC_D1_SRC = """
_SINC_SERIES_RADIUS = {radius!r}
_SINC_D1_COEFFS = {coeffs!r}


def _sinc_d1(z):
    z = np.asarray(z)
    small = np.abs(z) < _SINC_SERIES_RADIUS
    zs = np.where(small, z, 0.0)
    z2 = zs * zs
    acc = _SINC_D1_COEFFS[-1] + 0.0 * z2
    for c in _SINC_D1_COEFFS[-2::-1]:
        acc = c + z2 * acc
    series = zs * acc
    zl = np.where(small, 1.0, z)
    direct = (np.cos(zl) - np.sin(zl) / zl) / zl
    return np.where(small, series, direct)[()]
"""


def _literal(v: Any) -> str:
    if isinstance(v, bool):
        return repr(v)
    if isinstance(v, complex):
        return f"complex({_literal(v.real)}, {_literal(v.imag)})"
    f = float(v)
    if math.isfinite(f):
        return repr(f)
    return f"float({str(f)!r})"


def _program_source(outputs: List[I.Expr], n: int, name: str) -> str:
    prog = generate(outputs, n, "numpy", name)
    if any(key.startswith("_proc") for key in prog.namespace):
        raise CompileError("an opaque leaf (no lowering rule) cannot be exported")

    # the constants of the psi and grad programs share names (_c0, ...): prefix them
    lines = [
        f"_{name}{key} = {_literal(val)}"
        for key, val in sorted(prog.namespace.items())
        if re.fullmatch(r"_c\d+", key)
    ]
    src = re.sub(r"\b(_c\d+)\b", rf"_{name}\1", prog.source.rstrip())
    return "\n".join(lines + ["", "", src])


def export_source(cp: Any, grad: bool = True) -> str:
    """
    Source text of a standalone module for ``cp``'s exponent (and gradient).

    Parameters
    ----------
    cp :
        A :class:`~spxa.compile.process.CompiledProcess`.
    grad :
        Also export ``psi_and_grad``.
    """
    k = cp.kernel
    n = k.n_free
    outs: List[I.Expr] = [k.psi_expr]
    psi_src = _program_source(outs, n, "psi")
    grad_src = _program_source([k.psi_expr] + k.grad_exprs, n, "grad") if grad else ""
    body = psi_src + "\n" + grad_src
    if "_kve_dnu" in body:
        raise CompileError(
            "the order derivative of K_lambda (a free GH lambda_param) needs spxa; "
            "fix lambda_param to export the gradient"
        )
    needs_sps = "sps." in body
    helpers = ""
    if "_sinc(" in body:
        helpers += _SINC_SRC
    if "_sinc_d1(" in body:
        helpers += _SINC_D1_SRC.format(radius=_SINC_SERIES_RADIUS, coeffs=_SINC_D1_COEFFS)
    names = tuple(cp.names)
    theta0 = tuple(float(v) for v in cp.values)
    story = cp.story().replace('"""', "'''")
    out = [
        '"""',
        "Characteristic exponent generated by spxa.compile (standalone; NumPy only).",
        "",
        f"Process: {story}",
        "",
        "E[exp(i u X_t)] = exp(t psi(u)); theta holds the free parameters NAMES.",
        '"""',
        "",
        "import numpy as np",
    ]
    if needs_sps:
        out.append("import scipy.special as sps")
    out += [
        "",
        f"NAMES = {names!r}",
        f"THETA0 = ({', '.join(_literal(v) for v in theta0)}{',' if len(theta0) == 1 else ''})",
        helpers,
        "",
        psi_src,
        "",
    ]
    if grad:
        out += ["", grad_src, ""]
    out += [
        "",
        "def _args(u, theta):",
        "    th = THETA0 if theta is None else tuple(float(v) for v in theta)",
        "    if len(th) != len(NAMES):",
        '        raise ValueError(f"theta needs {len(NAMES)} values: {NAMES}")',
        "    return np.asarray(u, dtype=complex), [np.float64(v) for v in th]",
        "",
        "",
        "def psi(u, theta=None):",
        '    """psi(u; theta), shaped like u."""',
        "    uu, ps = _args(u, theta)",
        "    return np.broadcast_to(_kernel_psi(uu, *ps)[0], uu.shape).astype(complex)",
        "",
        "",
        "def char_func(u, t=1.0, theta=None):",
        '    """E[exp(i u X_t)]."""',
        "    return np.exp(float(t) * psi(u, theta))",
    ]
    if grad:
        out += [
            "",
            "",
            "def psi_and_grad(u, theta=None):",
            '    """psi and d psi / d theta (last axis, in NAMES order)."""',
            "    uu, ps = _args(u, theta)",
            "    res = _kernel_grad(uu, *ps)",
            "    value = np.broadcast_to(res[0], uu.shape).astype(complex)",
            "    g = np.empty(uu.shape + (len(NAMES),), dtype=complex)",
            "    for k in range(len(NAMES)):",
            "        g[..., k] = res[1 + k]",
            "    return value, g",
        ]
    return "\n".join(out).replace("\n\n\n\n", "\n\n\n") + "\n"
